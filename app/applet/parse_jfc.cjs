const lines = rawCsv.split('\n');
let currentCatId = 'c_sauce_jfc';
let products = [];
let displayOrder = 1;
let seenCodes = new Set();

for (let line of lines) {
  line = line.trim();
  if (!line || line.startsWith('ITEMNO') || line.startsWith(',,,,')) continue;
  
  if (line.startsWith('AMBIENT FOOD')) {
    currentCatId = 'c_sauce_jfc';
    continue;
  }
  if (line.startsWith('FROZEN GOODS')) {
    currentCatId = 'c_frozen_jfc';
    continue;
  }
  if (line.startsWith('NON-FOOD')) {
    currentCatId = 'c_jfc_nonfood';
    continue;
  }

  const parts = line.split(',');
  const itemCode = parts[0]?.trim();
  let rawDesc = parts[1]?.trim() || '';
  const casePrice = parseFloat(parts[2]?.trim()) || 0;

  if (!itemCode || !rawDesc || seenCodes.has(itemCode)) continue;
  seenCodes.add(itemCode);

  let cleanName = rawDesc.replace(/^[:*]+/, '').trim();
  cleanName = cleanName.replace(/^\([A-Z0-9]+\)\s*->\s*/, '').trim();

  let packSize = '';
  const match = cleanName.match(/(\d+(?:\/\d+)*(?:\.\d+)?\s*(?:KG|G|L|ML|P|PC|SHT|SH|OZ|M|CM)(?:\s*\(.*?\))?)$/i);
  if (match) {
    packSize = match[1].trim();
  }

  let catId = currentCatId;
  if (itemCode.startsWith('A') && currentCatId === 'c_sauce_jfc') {
    catId = 'c_rice';
  } else if (itemCode.startsWith('H') && currentCatId === 'c_sauce_jfc') {
    catId = 'c_alc';
  }

  products.push({
    id: itemCode,
    itemCode: itemCode,
    name: cleanName,
    categoryId: catId,
    supplierId: 's_jfc',
    casePrice: casePrice,
    packPrice: 0,
    packSize: packSize || '',
    displayOrder: displayOrder++,
    allowedBranchIds: [],
    active: true
  });
}

fs.writeFileSync('/app/applet/parse_result.json', JSON.stringify(products, null, 2));
console.log(`Parsed ${products.length} unique JFC products`);
